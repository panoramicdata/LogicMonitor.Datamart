namespace LogicMonitor.Datamart.Mapping;

/// <summary>
/// AutoMapper profile for mapping LogicMonitor Alert API objects to <see cref="AlertStoreItem"/>.
/// </summary>
public class AlertProfile : Profile
{
	/// <summary>
	/// Initializes a new instance of the <see cref="AlertProfile"/> class.
	/// </summary>
	public AlertProfile()
	{
		CreateAlertToAlertStoreItemMap();
		CreateAlertStoreItemToAlertMap();
	}

	private void CreateAlertToAlertStoreItemMap()
	{
		CreateMap<Alert, AlertStoreItem>()
			.IgnoreMembers(
				dest => dest.AlertRule, dest => dest.MonitorObjectGroup0, dest => dest.MonitorObjectGroup1, dest => dest.MonitorObjectGroup2,
				dest => dest.MonitorObjectGroup3, dest => dest.MonitorObjectGroup4, dest => dest.MonitorObjectGroup5, dest => dest.MonitorObjectGroup6,
				dest => dest.MonitorObjectGroup7, dest => dest.MonitorObjectGroup8, dest => dest.MonitorObjectGroup9, dest => dest.Id,
				dest => dest.DatamartCreated, dest => dest.DatamartLastModified, dest => dest.MonitorObjectGroup0Id, dest => dest.MonitorObjectGroup1Id,
				dest => dest.MonitorObjectGroup2Id, dest => dest.MonitorObjectGroup3Id, dest => dest.MonitorObjectGroup4Id, dest => dest.MonitorObjectGroup5Id,
				dest => dest.MonitorObjectGroup6Id, dest => dest.MonitorObjectGroup7Id, dest => dest.MonitorObjectGroup8Id, dest => dest.MonitorObjectGroup9Id)
				// Navigation properties
				.ForMember(
					dest => dest.LogicMonitorId,
					opts => opts.MapFrom(src => src.Id))
											
				// Auto generated by the database server
	
				// Handled manually and by EF during save as appropriate
		
				// The following can come in as 0, which means unassigned
				.ForMember(
					dest => dest.AlertRuleId,
					opts => opts.Ignore())
				.ForMember(
					dest => dest.AlertEscalationChainId,
					opts => opts.MapFrom(src => src.AlertEscalationChainId == 0 ? (int?)null : src.AlertEscalationChainId))
				.ForMember(
					dest => dest.AlertEscalationSubChainId,
					opts => opts.MapFrom(src => src.AlertEscalationSubChainId == 0 ? (int?)null : src.AlertEscalationSubChainId))
				// Manually set afterwards
										
				.ForMember(
					dest => dest.DetailMessageSubject,
					opts => opts.MapFrom(src => src.DetailMessage.Subject))
				.ForMember(
					dest => dest.DetailMessageBody,
					opts => opts.MapFrom(src => src.DetailMessage.Body))
				.ForMember(
					dest => dest.CustomColumn1,
					opts => opts.Ignore())
				.ForMember(
					dest => dest.CustomColumn2,
					opts => opts.Ignore())
				.ForMember(
					dest => dest.CustomColumn3,
					opts => opts.Ignore())
				.ForMember(
					dest => dest.CustomColumn4,
					opts => opts.Ignore())
				.ForMember(
					dest => dest.CustomColumn5,
					opts => opts.Ignore())
				.AfterMap<TruncateMappingAction<Alert, AlertStoreItem>>();
	}

	private void CreateAlertStoreItemToAlertMap()
	{
		CreateMap<AlertStoreItem, Alert>()
			.IgnoreMembers(
				dest => dest.AlertRuleId, dest => dest.AlertTriggerValue, dest => dest.AlertGroupEntityValue, dest => dest.AlertQuery,
				dest => dest.ClearExpression, dest => dest.CustomColumns, dest => dest.ExternalTicketUrl, dest => dest.LogPartition,
				dest => dest.LogMetadata, dest => dest.MonitorObjectGroups, dest => dest.Sdt, dest => dest.SessionId,
				dest => dest.LastUpdatedOnMs, dest => dest.SdtIds, dest => dest.ThresholdMetadata)
			.ForMember(
				dest => dest.DetailMessage,
				opts => opts.MapFrom(
					src => new AlertDetailMessage
					{
						Subject = src.DetailMessageSubject,
						Body = src.DetailMessageBody
					}
				)
			);
	}
}
